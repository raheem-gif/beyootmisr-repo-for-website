<?php
/**
 * Protected runtime storage in app/storage (users, logs, counters, backups).
 *
 * Shared hosting (Turbify) may ignore .htaccess, so nothing here relies on it:
 * every file that holds private data is a .php file that prints nothing when
 * requested over HTTP.
 *
 *   PHP-array files   "<?php defined('BM_APP') || exit; return [...];"
 *       adm_store_php_read(string $file): array
 *       adm_store_php_write(string $file, array $data): void      (var_export, atomic, opcache-safe)
 *
 *   Guarded JSON      "<?php exit; ?>\n{json}"
 *       adm_store_json_read(string $file, $default = [])
 *       adm_store_json_write(string $file, $data): void
 *
 *   Guarded JSON lines (append-only logs)
 *       adm_store_lines_append(string $file, array $entry): void
 *       adm_store_lines_read(string $file): array                 (oldest first)
 *
 *   adm_write_protected(string $file, string $contents): void  atomic write whose temp file is also .php
 *   adm_with_lock(string $name, callable $fn)                  run $fn under an exclusive flock
 *   adm_storage(string $rel = ''): string                      absolute path inside app/storage
 *   adm_strip_guard(string $raw): string                       remove the "<?php exit; ?>" prefix
 */
declare(strict_types=1);
defined('BM_APP') || exit;

const ADM_GUARD = "<?php exit; ?>\n";

/** Absolute path inside app/storage. */
function adm_storage(string $rel = ''): string
{
    return BM_STORAGE . ($rel !== '' ? '/' . ltrim($rel, '/') : '');
}

/** Create a storage sub-folder (with an index.html that blocks directory listings). */
function adm_storage_dir(string $rel): string
{
    $dir = adm_storage($rel);
    if (!is_dir($dir)) {
        if (!@mkdir($dir, 0755, true) && !is_dir($dir)) {
            throw new AdmUserError(adm_msg_unwritable($dir));
        }
    }
    if (!is_file($dir . '/index.html')) {
        @file_put_contents($dir . '/index.html', "<!doctype html><title>403</title>\n");
    }
    return $dir;
}

/**
 * Atomic write for private files. The temporary file also ends in .php and the
 * contents must start with a PHP guard, so even a leftover temp file is never
 * readable over HTTP.
 */
function adm_write_protected(string $file, string $contents): void
{
    $dir = dirname($file);
    if (!is_dir($dir) && !@mkdir($dir, 0755, true) && !is_dir($dir)) {
        throw new AdmUserError(adm_msg_unwritable($dir));
    }
    if (strpos($contents, '<?php') !== 0) {
        throw new RuntimeException('Protected storage must start with a PHP guard: ' . basename($file));
    }
    $tmp = $dir . '/.tmp-' . bin2hex(random_bytes(6)) . '.php';
    if (@file_put_contents($tmp, $contents, LOCK_EX) === false) {
        throw new AdmUserError(adm_msg_unwritable($dir));
    }
    @chmod($tmp, 0640);
    if (!@rename($tmp, $file)) {
        @unlink($tmp);
        throw new AdmUserError(adm_msg_unwritable($dir));
    }
    if (function_exists('opcache_invalidate')) {
        @opcache_invalidate($file, true);
    }
}

function adm_strip_guard(string $raw): string
{
    if (strpos($raw, '<?php exit; ?>') === 0) {
        $nl = strpos($raw, "\n");
        return $nl === false ? '' : (string) substr($raw, $nl + 1);
    }
    return $raw;
}

/** Read a PHP file that returns an array. */
function adm_store_php_read(string $file): array
{
    if (!is_file($file)) {
        return [];
    }
    $data = (static function (string $__f) {
        return include $__f;
    })($file);
    return is_array($data) ? $data : [];
}

function adm_store_php_write(string $file, array $data): void
{
    $php = "<?php\n// Generated by the Beyoot Misr admin panel. Do not edit by hand.\n"
        . "defined('BM_APP') || exit;\n\nreturn " . var_export($data, true) . ";\n";
    adm_write_protected($file, $php);
}

/** @return mixed */
function adm_store_json_read(string $file, $default = [])
{
    if (!is_file($file)) {
        return $default;
    }
    $raw = @file_get_contents($file);
    if ($raw === false) {
        return $default;
    }
    $data = json_decode(adm_strip_guard($raw), true);
    return json_last_error() === JSON_ERROR_NONE && $data !== null ? $data : $default;
}

function adm_store_json_write(string $file, $data): void
{
    $json = json_encode($data, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES | JSON_PRETTY_PRINT);
    if ($json === false) {
        throw new RuntimeException('Could not encode ' . basename($file));
    }
    adm_write_protected($file, ADM_GUARD . $json . "\n");
}

/** Append one JSON line to a guarded log file (created with the guard on first use). */
function adm_store_lines_append(string $file, array $entry): void
{
    $line = json_encode($entry, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES);
    if ($line === false) {
        return;
    }
    if (!is_file($file)) {
        $dir = dirname($file);
        if (!is_dir($dir)) {
            @mkdir($dir, 0755, true);
        }
        $h = @fopen($file, 'x');
        if ($h) {
            fwrite($h, ADM_GUARD);
            fclose($h);
        }
    }
    if (@file_put_contents($file, $line . "\n", FILE_APPEND | LOCK_EX) === false) {
        throw new AdmUserError(adm_msg_unwritable(dirname($file)));
    }
}

/** @return array[] entries, oldest first */
function adm_store_lines_read(string $file): array
{
    if (!is_file($file)) {
        return [];
    }
    $raw = (string) @file_get_contents($file);
    $out = [];
    foreach (explode("\n", adm_strip_guard($raw)) as $line) {
        if ($line === '') {
            continue;
        }
        $row = json_decode($line, true);
        if (is_array($row)) {
            $out[] = $row;
        }
    }
    return $out;
}

/**
 * Run $fn while holding an exclusive lock (app/storage/<name>.lock).
 * @return mixed whatever $fn returns
 */
function adm_with_lock(string $name, callable $fn)
{
    $name = preg_replace('/[^a-z0-9_-]/', '', strtolower($name)) ?: 'admin';
    $file = adm_storage($name . '.lock');
    $h = @fopen($file, 'c');
    if ($h) {
        flock($h, LOCK_EX);
    }
    try {
        return $fn();
    } finally {
        if ($h) {
            flock($h, LOCK_UN);
            fclose($h);
        }
    }
}

/** Long-lived random secret for HMACs (rate-limit keys, audit IP hashes). */
function adm_secret(): string
{
    static $secret = null;
    if ($secret !== null) {
        return $secret;
    }
    $file = adm_storage('secret.php');
    $data = adm_store_php_read($file);
    if (empty($data['key']) || !is_string($data['key'])) {
        $data = ['key' => bin2hex(random_bytes(32)), 'created_at' => date('c')];
        try {
            adm_store_php_write($file, $data);
        } catch (Throwable $e) {
            // Storage not writable: keep a per-request key; the health check reports the folder.
        }
    }
    return $secret = (string) $data['key'];
}

/** Arabic message for a folder that cannot be written (names it relative to the site root). */
function adm_msg_unwritable(string $path): string
{
    if (is_file($path)) {
        return 'تعذّر الحفظ لأن الملف «' . adm_rel($path) . '» غير قابل للكتابة على الاستضافة. '
            . 'افتح «مدير الملفات» (File Manager) في لوحة Turbify، واضبط صلاحيات الملف على 644 '
            . '(أو 664) وصلاحيات مجلده على 755 ثم أعد المحاولة.';
    }
    return 'تعذّر الحفظ لأن المجلد «' . adm_rel($path) . '» غير قابل للكتابة على الاستضافة. '
        . 'افتح «مدير الملفات» (File Manager) في لوحة Turbify، واضبط صلاحيات هذا المجلد على 755 '
        . '(أو 775 إن لم تكفِ) ثم أعد المحاولة.';
}

/** Path relative to the public site root, for messages ("app/content"). */
function adm_rel(string $abs): string
{
    $root = rtrim(str_replace('\\', '/', BM_PUBLIC), '/') . '/';
    $abs = str_replace('\\', '/', $abs);
    if (strpos($abs, $root) === 0) {
        $rel = substr($abs, strlen($root));
        return $rel === '' ? '/' : $rel;
    }
    return basename($abs);
}
