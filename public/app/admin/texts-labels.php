/** Arabic label for a texts.json field path. */
function adm_text_label(array $path): string
{
    $labels = adm_text_labels();
    $key = (string) end($path);
    $full = implode('.', $path);
    if (isset($labels[$full])) {
        return $labels[$full];
    }
    if (count($path) >= 2 && isset($labels[$path[0] . '.' . $key])) {
        return $labels[$path[0] . '.' . $key];
    }
    if (isset($labels[$key])) {
        return $labels[$key];
    }
    if (preg_match('/^(.+)_title$/', $key)) {
        return 'عنوان: ' . str_replace('_', ' ', $key);
    }
    if (preg_match('/^(.+)_label$/', $key)) {
        return 'عبارة: ' . str_replace('_', ' ', $key);
    }
    return str_replace('_', ' ', $key);
}
