#!/usr/bin/env bash
# Build the site and create upload packages for Turbify (cPanel File Manager → public_html).
#
#   dist/beyoot-misr-site-full.zip    first installation: the whole site
#   dist/beyoot-misr-code-update.zip  later code updates: everything EXCEPT content,
#                                     uploads, runtime storage, generated pages and the
#                                     root .htaccess, so the content edited in the admin
#                                     panel is never overwritten (and a .htaccess deleted
#                                     because of a 500 error is not brought back). It
#                                     carries the current texts as app/lib/texts-defaults
#                                     .json.php: text keys added by new templates show the
#                                     document's wording until edited. After uploading it,
#                                     press «إعادة بناء الموقع» in the admin dashboard.
set -euo pipefail
cd "$(dirname "$0")/.."
DIST="$(pwd)/dist"

php public/app/build.php --strict
python3 -I tools/check-links.py public

mkdir -p dist
rm -f dist/beyoot-misr-site-full.zip dist/beyoot-misr-code-update.zip

cd public
# Runtime data never ships: storage keeps only its guard file, uploads only their guard files.
COMMON_EXCLUDES=(-x 'app/storage/*' -x '*.tmp' -x '*/.DS_Store')
zip -qr ../dist/beyoot-misr-site-full.zip . "${COMMON_EXCLUDES[@]}" -x 'uploads/images/*' -x 'uploads/reports/*'
zip -q ../dist/beyoot-misr-site-full.zip app/storage/index.html uploads/images/index.html uploads/reports/index.html

zip -qr ../dist/beyoot-misr-code-update.zip . "${COMMON_EXCLUDES[@]}" \
  -x 'app/content/*' -x 'uploads/*' -x '*.html' -x 'sitemap.xml' -x 'robots.txt' -x '.htaccess'
# Guard files and admin/static HTML that are not generated by the build:
zip -q ../dist/beyoot-misr-code-update.zip app/index.html app/lib/index.html app/templates/index.html app/storage/index.html
# Default texts for new keys (the server's own texts.json.php always wins; see bm_merge_texts()).
STAGE="$(mktemp -d)"
mkdir -p "$STAGE/app/lib"
cp app/content/texts.json.php "$STAGE/app/lib/texts-defaults.json.php"
(cd "$STAGE" && zip -q "$DIST/beyoot-misr-code-update.zip" app/lib/texts-defaults.json.php)
rm -rf "$STAGE"
cd ..

ls -la dist
unzip -l dist/beyoot-misr-site-full.zip | tail -1
unzip -l dist/beyoot-misr-code-update.zip | tail -1
